def verified_pairs() -> list[tuple[str, str]]:
    """人工核实过的 (主名, 别名) 对。只取 aliases，ambiguous 一律不取——
    那是跨人歧义，并进来就会把两个人的戏搅成一个人。s4 归并时优先落这些。"""
    out = []
    for p in PRESETS.values():
        canon = p["canonical"]
        for a in p.get("aliases") or []:
            if a and a != canon:
                out.append((canon, a))
    return out


