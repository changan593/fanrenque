def is_generic(name: str) -> bool:
    """严口径：这个称呼是不是泛称。泛称不进人物名单，也不参与别名归并。"""
    n = (name or "").strip()
    if not n or n in GENERIC_EXACT:
        return True
    if n.endswith("（群体）") or n.endswith("(群体)"):
        return True
    if any(n.endswith(r) for r in GENERIC_ROOTS):
        return True
    return any(w in n for w in GENERIC_CONTAINS)


def is_unnamed(name: str) -> bool:
    """宽口径：说话人 / 在场者是不是没名字的角色。是就不要求它登记在人物名单里。"""
    n = (name or "").strip()
    return is_generic(n) or any(w in n for w in UNNAMED_WORDS)


def base_name(name: str) -> str:
    """「姚安饶（二开分身）」→「姚安饶」。括号注记不参与身份判定。"""
    return re.split(r"[（(]", (name or "").strip())[0].strip()


def is_known(name: str, known: set[str]) -> bool:
    """人物名单里有 → 认；没名字的角色（宽口径）→ 放行；带括号注记的剥掉括号再比一次。"""
    n = (name or "").strip()
    if n in known or is_unnamed(n):
        return True
    b = base_name(n)
    return bool(b) and b in known


# ---------------------------------------------------------------- 3. 别名解析
def build_resolver(index_chars: list[dict]) -> tuple[Callable[[str], tuple[str, bool]], dict]:
    """
    别名 → 主名。返回 (resolve, ambiguity)，resolve(name) -> (归属, 是否存疑)。

    三级，优先级从高到低，**级别不够就不并**：

      1. PRESETS（人工逐字核实过的身份）          红儿 → 姚望舒
      2. 索引里**只有一个主名认领**的别名            三只眼 → 唐真
      3. 多方认领 / 本身也是主名 / 人工标了存疑    「师姐」原样保留，标存疑

    第三级**不猜**。把别名表拉平成字典、后写覆盖先写，是 s11 踩过的坑：
    `红儿` 同时被 `姚望舒`（380 章）和 `师姐`（26 章）认领，拉平后落到了 `师姐` 头上，
    S01E01 的角色表里就有「师姐」而没有姚望舒。
    """
    canon = {c["canonical_name"] for c in index_chars}

    claims: dict[str, list[str]] = defaultdict(list)
    for c in index_chars:
        for a in c.get("aliases") or []:
            claims[a].append(c["canonical_name"])

    preset_map, preset_block = {}, set()
    for p in PRESETS.values():
        for a in p["aliases"]:
            preset_map[a] = p["canonical"]
        preset_block.update(p.get("ambiguous") or [])
        preset_block.update(p.get("exclude") or [])

    ambiguity = {a: sorted(set(o)) for a, o in claims.items()
                 if len(set(o)) > 1 or a in canon}

    def resolve(name: str) -> tuple[str, bool]:
        if name in preset_block:            # 人工明说过它跨人，别并
            return name, True
        if name in preset_map:              # 人工核实过的身份，最高优先
            return preset_map[name], False
        if name in canon:                   # 它自己就是主名，优先算它自己
            return name, name in ambiguity
        owners = sorted(set(claims.get(name, [])))
        if len(owners) == 1:
            return owners[0], False
        if len(owners) > 1:                 # 多方认领，不猜
            return name, True
        return name, False                  # 索引里没有，按字面

    return resolve, ambiguity


